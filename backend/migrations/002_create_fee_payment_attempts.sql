CREATE TABLE IF NOT EXISTS FEE_PAYMENT_ATTEMPTS (
  PAYMENT_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  FEE_SOURCE ENUM('FEE_TRANSACTION', 'ACCOUNTING_LEDGER') NOT NULL,
  FEE_RECORD_ID INT UNSIGNED NOT NULL,
  IDEMPOTENCY_KEY VARCHAR(128) NOT NULL,
  TRANSACTION_REFERENCE VARCHAR(100) NOT NULL UNIQUE,
  AMOUNT DECIMAL(10, 2) NOT NULL,
  STATUS ENUM('SUCCEEDED') NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_fee_payment_idempotency (STUDENT_ID, IDEMPOTENCY_KEY),
  INDEX idx_fee_payment_record (FEE_SOURCE, FEE_RECORD_ID),
  CONSTRAINT fk_fee_payment_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;