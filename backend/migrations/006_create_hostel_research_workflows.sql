CREATE TABLE IF NOT EXISTS HOSTEL_BUILDINGS (
  BUILDING_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  NAME VARCHAR(140) NOT NULL UNIQUE,
  STATUS ENUM('ACTIVE', 'CLOSED') NOT NULL DEFAULT 'ACTIVE',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS HOSTEL_ROOMS (
  ROOM_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  BUILDING_ID INT UNSIGNED NOT NULL,
  ROOM_NUMBER VARCHAR(30) NOT NULL,
  CAPACITY SMALLINT UNSIGNED NOT NULL,
  STATUS ENUM('ACTIVE', 'MAINTENANCE', 'CLOSED') NOT NULL DEFAULT 'ACTIVE',
  UNIQUE KEY uq_hostel_room (BUILDING_ID, ROOM_NUMBER),
  CONSTRAINT chk_hostel_room_capacity CHECK (CAPACITY > 0),
  CONSTRAINT fk_hostel_room_building FOREIGN KEY (BUILDING_ID) REFERENCES HOSTEL_BUILDINGS(BUILDING_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS HOSTEL_APPLICATIONS (
  APPLICATION_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  ACADEMIC_YEAR VARCHAR(9) NOT NULL,
  PREFERRED_BUILDING_ID INT UNSIGNED,
  REASON VARCHAR(500),
  STATUS ENUM('REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED') NOT NULL DEFAULT 'REQUESTED',
  REVIEWED_BY INT UNSIGNED,
  REVIEWED_AT DATETIME,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_hostel_student_year (STUDENT_ID, ACADEMIC_YEAR),
  CONSTRAINT fk_hostel_application_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_hostel_application_building FOREIGN KEY (PREFERRED_BUILDING_ID) REFERENCES HOSTEL_BUILDINGS(BUILDING_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_hostel_application_reviewer FOREIGN KEY (REVIEWED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS HOSTEL_ALLOCATIONS (
  ALLOCATION_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  APPLICATION_ID BIGINT UNSIGNED NOT NULL UNIQUE,
  STUDENT_ID INT UNSIGNED NOT NULL,
  ROOM_ID INT UNSIGNED NOT NULL,
  BED_NUMBER SMALLINT UNSIGNED NOT NULL,
  STATUS ENUM('ACTIVE', 'COMPLETED') NOT NULL DEFAULT 'ACTIVE',
  CHECKED_IN_AT DATETIME,
  CHECKED_OUT_AT DATETIME,
  UNIQUE KEY uq_hostel_bed (ROOM_ID, BED_NUMBER),
  CONSTRAINT fk_hostel_allocation_application FOREIGN KEY (APPLICATION_ID) REFERENCES HOSTEL_APPLICATIONS(APPLICATION_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_hostel_allocation_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_hostel_allocation_room FOREIGN KEY (ROOM_ID) REFERENCES HOSTEL_ROOMS(ROOM_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS HOSTEL_MAINTENANCE_REQUESTS (
  REQUEST_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  ALLOCATION_ID BIGINT UNSIGNED NOT NULL,
  CATEGORY VARCHAR(80) NOT NULL,
  DESCRIPTION VARCHAR(1000) NOT NULL,
  STATUS ENUM('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CANCELLED') NOT NULL DEFAULT 'OPEN',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_hostel_maintenance_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_hostel_maintenance_allocation FOREIGN KEY (ALLOCATION_ID) REFERENCES HOSTEL_ALLOCATIONS(ALLOCATION_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS RESEARCH_PROJECTS (
  PROJECT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TITLE VARCHAR(180) NOT NULL,
  DESCRIPTION TEXT NOT NULL,
  SUPERVISOR VARCHAR(140),
  PROGRAM_ID INT UNSIGNED,
  APPLICATION_DEADLINE DATE NOT NULL,
  CAPACITY SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  STATUS ENUM('OPEN', 'CLOSED') NOT NULL DEFAULT 'OPEN',
  CREATED_BY INT UNSIGNED NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_research_capacity CHECK (CAPACITY > 0),
  CONSTRAINT fk_research_creator FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS RESEARCH_APPLICATIONS (
  APPLICATION_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  PROJECT_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  STATEMENT VARCHAR(2000) NOT NULL,
  STATUS ENUM('SUBMITTED', 'UNDER_REVIEW', 'ACCEPTED', 'REJECTED', 'WITHDRAWN') NOT NULL DEFAULT 'SUBMITTED',
  REVIEWED_BY INT UNSIGNED,
  REVIEWED_AT DATETIME,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_research_student_project (PROJECT_ID, STUDENT_ID),
  CONSTRAINT fk_research_application_project FOREIGN KEY (PROJECT_ID) REFERENCES RESEARCH_PROJECTS(PROJECT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_research_application_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_research_application_reviewer FOREIGN KEY (REVIEWED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;