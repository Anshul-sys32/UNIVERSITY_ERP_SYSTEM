CREATE TABLE IF NOT EXISTS USER_MODULE_POLICIES (
  USER_ID INT UNSIGNED NOT NULL,
  MODULE_KEY VARCHAR(64) NOT NULL,
  CAN_READ TINYINT(1) NOT NULL DEFAULT 0,
  CAN_WRITE TINYINT(1) NOT NULL DEFAULT 0,
  ROW_SCOPE ENUM('self', 'assigned_course', 'university') NOT NULL DEFAULT 'self',
  SIDEBAR_VISIBLE TINYINT(1) NOT NULL DEFAULT 0,
  UPDATED_BY INT UNSIGNED,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (USER_ID, MODULE_KEY),
  CONSTRAINT fk_user_module_user FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT fk_user_module_updated_by FOREIGN KEY (UPDATED_BY) REFERENCES USERS(USER_ID) ON DELETE SET NULL,
  CONSTRAINT chk_user_module_write_requires_read CHECK (CAN_WRITE = 0 OR CAN_READ = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

