  MODIFY ROLE ENUM('STUDENT', 'FACULTY', 'EMPLOYEE', 'ADMIN', 'LIBRARIAN', 'ACCOUNTANT', 'MERCHANT') NOT NULL;

CREATE TABLE IF NOT EXISTS CAMPUS_WALLETS (
  WALLET_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL UNIQUE,
  BALANCE DECIMAL(12, 2) NOT NULL DEFAULT 0,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT chk_wallet_balance_nonnegative CHECK (BALANCE >= 0),
  CONSTRAINT fk_wallet_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS WALLET_REWARD_POLICIES (
  POLICY_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  POLICY_NAME VARCHAR(140) NOT NULL,
  PERIOD_CODE VARCHAR(30) NOT NULL,
  PROGRAM_ID INT UNSIGNED,
  SEMESTER TINYINT UNSIGNED,
  BUDGET_AMOUNT DECIMAL(12, 2) NOT NULL,
  PER_STUDENT_CAP DECIMAL(10, 2) NOT NULL,
  EXPIRES_AT DATE,
  STATUS ENUM('ACTIVE', 'PAUSED', 'CLOSED') NOT NULL DEFAULT 'ACTIVE',
  CREATED_BY INT UNSIGNED NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_wallet_policy_amounts CHECK (BUDGET_AMOUNT > 0 AND PER_STUDENT_CAP > 0),
  CONSTRAINT fk_wallet_policy_creator FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS WALLET_REWARD_REQUESTS (
  REQUEST_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  POLICY_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  COURSE_ID INT UNSIGNED NOT NULL,
  REQUESTED_BY INT UNSIGNED NOT NULL,
  AMOUNT DECIMAL(10, 2) NOT NULL,
  REASON VARCHAR(240) NOT NULL,
  EVIDENCE_REFERENCE VARCHAR(500),
  STATUS ENUM('REQUESTED', 'APPROVED', 'REJECTED', 'ISSUED') NOT NULL DEFAULT 'REQUESTED',
  REVIEWED_BY INT UNSIGNED,
  REVIEWED_AT DATETIME,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_wallet_reward_request_amount CHECK (AMOUNT > 0),
  CONSTRAINT fk_wallet_request_policy FOREIGN KEY (POLICY_ID) REFERENCES WALLET_REWARD_POLICIES(POLICY_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_request_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_request_course FOREIGN KEY (COURSE_ID) REFERENCES COURSES(COURSE_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_request_actor FOREIGN KEY (REQUESTED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_request_reviewer FOREIGN KEY (REVIEWED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MERCHANT_ACCOUNTS (
  MERCHANT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USER_ID INT UNSIGNED NOT NULL UNIQUE,
  DISPLAY_NAME VARCHAR(140) NOT NULL,
  STATUS ENUM('PENDING', 'ACTIVE', 'SUSPENDED') NOT NULL DEFAULT 'PENDING',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_merchant_user FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MERCHANT_CATALOG_ITEMS (
  ITEM_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MERCHANT_ID INT UNSIGNED NOT NULL,
  ITEM_NAME VARCHAR(140) NOT NULL,
  DESCRIPTION VARCHAR(300),
  PRICE_CREDITS DECIMAL(10, 2) NOT NULL,
  IS_AVAILABLE TINYINT(1) NOT NULL DEFAULT 1,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_catalog_price CHECK (PRICE_CREDITS > 0),
  CONSTRAINT fk_catalog_merchant FOREIGN KEY (MERCHANT_ID) REFERENCES MERCHANT_ACCOUNTS(MERCHANT_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CAMPUS_WALLET_ORDERS (
  ORDER_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  MERCHANT_ID INT UNSIGNED NOT NULL,
  ITEM_ID INT UNSIGNED NOT NULL,
  ITEM_NAME VARCHAR(140) NOT NULL,
  QUANTITY SMALLINT UNSIGNED NOT NULL,
  UNIT_PRICE DECIMAL(10, 2) NOT NULL,
  TOTAL_CREDITS DECIMAL(12, 2) NOT NULL,
  IDEMPOTENCY_KEY VARCHAR(128) NOT NULL,
  STATUS ENUM('PAID', 'REFUNDED') NOT NULL DEFAULT 'PAID',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_wallet_order_retry (STUDENT_ID, IDEMPOTENCY_KEY),
  CONSTRAINT chk_wallet_order_quantity CHECK (QUANTITY BETWEEN 1 AND 20),
  CONSTRAINT fk_wallet_order_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_order_merchant FOREIGN KEY (MERCHANT_ID) REFERENCES MERCHANT_ACCOUNTS(MERCHANT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_order_item FOREIGN KEY (ITEM_ID) REFERENCES MERCHANT_CATALOG_ITEMS(ITEM_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS WALLET_LEDGER_ENTRIES (
  LEDGER_ENTRY_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  ENTRY_TYPE ENUM('CREDIT', 'DEBIT', 'REVERSAL') NOT NULL,
  AMOUNT DECIMAL(12, 2) NOT NULL,
  REASON_CODE VARCHAR(60) NOT NULL,
  DESCRIPTION VARCHAR(240) NOT NULL,
  POLICY_ID INT UNSIGNED,
  ORDER_ID BIGINT UNSIGNED,
  ACTOR_USER_ID INT UNSIGNED NOT NULL,
  IDEMPOTENCY_KEY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_wallet_ledger_idempotency (STUDENT_ID, IDEMPOTENCY_KEY),
  INDEX idx_wallet_ledger_student_time (STUDENT_ID, CREATED_AT),
  CONSTRAINT chk_wallet_ledger_amount CHECK (AMOUNT > 0),
  CONSTRAINT fk_wallet_ledger_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_ledger_policy FOREIGN KEY (POLICY_ID) REFERENCES WALLET_REWARD_POLICIES(POLICY_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_ledger_order FOREIGN KEY (ORDER_ID) REFERENCES CAMPUS_WALLET_ORDERS(ORDER_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_wallet_ledger_actor FOREIGN KEY (ACTOR_USER_ID) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;