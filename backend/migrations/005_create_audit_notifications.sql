CREATE TABLE IF NOT EXISTS AUDIT_EVENTS (
  AUDIT_EVENT_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ACTOR_USER_ID INT UNSIGNED NOT NULL,
  REQUEST_ID CHAR(36) NOT NULL,
  ACTION VARCHAR(12) NOT NULL,
  RESOURCE VARCHAR(255) NOT NULL,
  HTTP_STATUS SMALLINT UNSIGNED NOT NULL,
  REASON VARCHAR(240),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_audit_actor_time (ACTOR_USER_ID, CREATED_AT),
  INDEX idx_audit_resource_time (RESOURCE(100), CREATED_AT),
  CONSTRAINT fk_audit_actor FOREIGN KEY (ACTOR_USER_ID) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS IN_APP_NOTIFICATIONS (
  NOTIFICATION_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USER_ID INT UNSIGNED NOT NULL,
  TITLE VARCHAR(160) NOT NULL,
  MESSAGE VARCHAR(500) NOT NULL,
  NOTIFICATION_TYPE VARCHAR(40) NOT NULL,
  RESOURCE_PATH VARCHAR(255),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  READ_AT DATETIME,
  INDEX idx_notification_user_time (USER_ID, CREATED_AT),
  CONSTRAINT fk_notification_user FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;