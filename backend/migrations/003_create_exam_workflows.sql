CREATE TABLE IF NOT EXISTS EXAM_SESSIONS (
  EXAM_SESSION_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  COURSE_ID INT UNSIGNED NOT NULL,
  EXAM_CODE VARCHAR(40) NOT NULL UNIQUE,
  EXAM_TYPE VARCHAR(80) NOT NULL,
  EXAM_DATE DATE NOT NULL,
  START_TIME TIME NOT NULL,
  END_TIME TIME NOT NULL,
  VENUE VARCHAR(180),
  MAX_SCORE DECIMAL(6, 2) NOT NULL DEFAULT 100,
  REGISTRATION_DEADLINE DATE NOT NULL,
  STATUS ENUM('DRAFT', 'OPEN', 'CLOSED', 'PUBLISHED', 'CANCELLED') NOT NULL DEFAULT 'DRAFT',
  CREATED_BY INT UNSIGNED NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_exam_sessions_course_date (COURSE_ID, EXAM_DATE),
  CONSTRAINT fk_exam_session_course FOREIGN KEY (COURSE_ID) REFERENCES COURSES(COURSE_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_exam_session_creator FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS EXAM_REGISTRATIONS (
  EXAM_REGISTRATION_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  EXAM_SESSION_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  STATUS ENUM('REGISTERED', 'CANCELLED') NOT NULL DEFAULT 'REGISTERED',
  REGISTERED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_exam_student (EXAM_SESSION_ID, STUDENT_ID),
  CONSTRAINT fk_exam_registration_session FOREIGN KEY (EXAM_SESSION_ID) REFERENCES EXAM_SESSIONS(EXAM_SESSION_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_exam_registration_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS EXAM_MARKS (
  EXAM_MARK_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  EXAM_SESSION_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  SCORE DECIMAL(6, 2) NOT NULL,
  MAX_SCORE DECIMAL(6, 2) NOT NULL,
  STATUS ENUM('DRAFT', 'SUBMITTED', 'APPROVED', 'PUBLISHED') NOT NULL DEFAULT 'DRAFT',
  UPDATED_BY INT UNSIGNED NOT NULL,
  APPROVED_BY INT UNSIGNED,
  APPROVED_AT DATETIME,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_exam_mark_student (EXAM_SESSION_ID, STUDENT_ID),
  CONSTRAINT fk_exam_marks_session FOREIGN KEY (EXAM_SESSION_ID) REFERENCES EXAM_SESSIONS(EXAM_SESSION_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_exam_marks_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_exam_marks_actor FOREIGN KEY (UPDATED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_exam_marks_approver FOREIGN KEY (APPROVED_BY) REFERENCES USERS(USER_ID)
    ON DELETE RESTRICT,
  CONSTRAINT chk_exam_marks_score CHECK (SCORE >= 0 AND MAX_SCORE > 0 AND SCORE <= MAX_SCORE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;