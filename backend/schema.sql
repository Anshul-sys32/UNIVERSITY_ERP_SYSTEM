CREATE DATABASE IF NOT EXISTS university_erp
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE university_erp;

CREATE TABLE IF NOT EXISTS USERS (
  USER_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USERNAME VARCHAR(100) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR(255) NOT NULL,
  ROLE ENUM('STUDENT', 'FACULTY', 'EMPLOYEE', 'ADMIN', 'LIBRARIAN', 'ACCOUNTANT') NOT NULL,
  IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS STUDENTS (
  STUDENT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ROLL_NUMBER VARCHAR(30) UNIQUE,
  ADMISSION_NUMBER VARCHAR(50) UNIQUE,
  FIRST_NAME VARCHAR(80) NOT NULL,
  LAST_NAME VARCHAR(80),
  GENDER VARCHAR(20),
  DOB DATE,
  EMAIL VARCHAR(160) NOT NULL UNIQUE,
  PHONE_NUMBER VARCHAR(25),
  ADDRESS_PERMANENT TEXT,
  ADDRESS_CURRENT TEXT,
  PROGRAM_ID INT UNSIGNED,
  DEPARTMENT_ID INT UNSIGNED,
  BATCH_YEAR SMALLINT UNSIGNED,
  CURRENT_SEMESTER TINYINT UNSIGNED,
  ADMISSION_DATE DATE,
  PARENT_GUARDIAN_NAME VARCHAR(160),
  PARENT_GUARDIAN_PHONE VARCHAR(25),
  PHOTO_URL VARCHAR(500),
  USER_ID INT UNSIGNED UNIQUE,
  STATUS ENUM('ACTIVE', 'INACTIVE', 'GRADUATED') NOT NULL DEFAULT 'ACTIVE',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_students_user FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
    ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS FACULTY (
  FACULTY_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USER_ID INT UNSIGNED NOT NULL UNIQUE,
  FIRST_NAME VARCHAR(80) NOT NULL,
  LAST_NAME VARCHAR(80),
  DEPARTMENT VARCHAR(160),
  EMAIL VARCHAR(160) NOT NULL UNIQUE,
  PHONE_NUMBER VARCHAR(25),
  DESIGNATION VARCHAR(120),
  STATUS ENUM('ACTIVE', 'INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_faculty_user FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS FACULTY_QUESTIONS (
  QUESTION_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  FACULTY_ID INT UNSIGNED NOT NULL,
  SUBJECT VARCHAR(160) NOT NULL,
  QUESTION_TEXT TEXT NOT NULL,
  QUESTION_TYPE ENUM('SHORT_ANSWER', 'MCQ') NOT NULL DEFAULT 'SHORT_ANSWER',
  OPTIONS_JSON JSON,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_questions_faculty FOREIGN KEY (FACULTY_ID) REFERENCES FACULTY(FACULTY_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS FACULTY_FORMS (
  FORM_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  FACULTY_ID INT UNSIGNED NOT NULL,
  TITLE VARCHAR(180) NOT NULL,
  QUESTIONS_JSON JSON NOT NULL,
  STATUS ENUM('DRAFT', 'PUBLISHED') NOT NULL DEFAULT 'DRAFT',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_forms_faculty FOREIGN KEY (FACULTY_ID) REFERENCES FACULTY(FACULTY_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ASSIGNMENTS (
  ASSIGNMENT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  TITLE VARCHAR(180) NOT NULL,
  DESCRIPTION TEXT,
  DUE_DATE DATE NOT NULL,
  STATUS ENUM('PENDING', 'SUBMITTED', 'COMPLETED', 'OVERDUE') NOT NULL DEFAULT 'PENDING',
  FACULTY_NAME VARCHAR(160),
  FACULTY_EMAIL VARCHAR(160),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_assignments_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS COURSES (
  COURSE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  COURSE_CODE VARCHAR(30) NOT NULL UNIQUE,
  TITLE VARCHAR(180) NOT NULL,
  CREDITS DECIMAL(4, 1) NOT NULL DEFAULT 0,
  SEMESTER TINYINT UNSIGNED NOT NULL,
  DEPARTMENT VARCHAR(160),
  COURSE_TYPE ENUM('CORE', 'ELECTIVE', 'OPEN_ELECTIVE') NOT NULL DEFAULT 'CORE',
  FACULTY_ID INT UNSIGNED,
  CAPACITY INT UNSIGNED NOT NULL DEFAULT 60,
  IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
  CONSTRAINT fk_course_faculty FOREIGN KEY (FACULTY_ID) REFERENCES FACULTY(FACULTY_ID)
    ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS COURSE_REGISTRATIONS (
  REGISTRATION_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  COURSE_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  ACADEMIC_YEAR VARCHAR(9) NOT NULL,
  STATUS ENUM('REGISTERED', 'DROPPED', 'COMPLETED') NOT NULL DEFAULT 'REGISTERED',
  REGISTERED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_course_student_year (COURSE_ID, STUDENT_ID, ACADEMIC_YEAR),
  CONSTRAINT fk_registration_course FOREIGN KEY (COURSE_ID) REFERENCES COURSES(COURSE_ID)
    ON DELETE CASCADE,
  CONSTRAINT fk_registration_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS TIMETABLE_SLOTS (
  SLOT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  COURSE_ID INT UNSIGNED NOT NULL,
  DAY_OF_WEEK ENUM('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY') NOT NULL,
  START_TIME TIME NOT NULL,
  END_TIME TIME NOT NULL,
  ROOM VARCHAR(80),
  CONSTRAINT fk_timetable_course FOREIGN KEY (COURSE_ID) REFERENCES COURSES(COURSE_ID)
    ON DELETE CASCADE,
  UNIQUE KEY uq_course_slot (COURSE_ID, DAY_OF_WEEK, START_TIME)
);

CREATE TABLE IF NOT EXISTS ATTENDANCE_LOGS (
  ATTENDANCE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  COURSE_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  FACULTY_ID INT UNSIGNED,
  LECTURE_DATE DATE NOT NULL,
  STATUS ENUM('PRESENT', 'ABSENT', 'ON_DUTY') NOT NULL,
  RECORDED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_attendance_student_course_date (COURSE_ID, STUDENT_ID, LECTURE_DATE),
  CONSTRAINT fk_attendance_course FOREIGN KEY (COURSE_ID) REFERENCES COURSES(COURSE_ID)
    ON DELETE CASCADE,
  CONSTRAINT fk_attendance_log_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE,
  CONSTRAINT fk_attendance_faculty FOREIGN KEY (FACULTY_ID) REFERENCES FACULTY(FACULTY_ID)
    ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS FEE_TRANSACTIONS (
  FEE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  DETAIL VARCHAR(180) NOT NULL,
  DUE_DATE DATE,
  AMOUNT DECIMAL(10, 2) NOT NULL,
  TRANSACTION_ID VARCHAR(80),
  STATUS ENUM('PAID', 'UNPAID', 'PENDING') NOT NULL DEFAULT 'UNPAID',
  PAID_AT DATETIME,
  CONSTRAINT fk_fees_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS LIBRARY_BOOKS (
  ISSUE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  TITLE VARCHAR(200) NOT NULL,
  ISSUE_DATE DATE NOT NULL,
  RETURN_DATE DATE,
  STATUS ENUM('ISSUED', 'RETURNED', 'OVERDUE') NOT NULL DEFAULT 'ISSUED',
  CONSTRAINT fk_library_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS CAMPUS_EVENTS (
  EVENT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TITLE VARCHAR(180) NOT NULL,
  EVENT_DATE DATE NOT NULL,
  LOCATION VARCHAR(180),
  TYPE ENUM('EVENT', 'PLACEMENT', 'WORKSHOP') NOT NULL DEFAULT 'EVENT',
  DESCRIPTION TEXT,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PLACEMENT_DRIVES (
  DRIVE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  COMPANY_NAME VARCHAR(180) NOT NULL,
  ROLE_TITLE VARCHAR(180) NOT NULL,
  ELIGIBILITY VARCHAR(240),
  DRIVE_DATE DATE NOT NULL,
  APPLICATION_DEADLINE DATE NOT NULL,
  LOCATION VARCHAR(180),
  PACKAGE VARCHAR(100),
  DESCRIPTION TEXT,
  STATUS ENUM('OPEN', 'CLOSED', 'COMPLETED') NOT NULL DEFAULT 'OPEN',
  CREATED_BY INT UNSIGNED,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_drive_user FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID)
    ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS PLACEMENT_APPLICATIONS (
  APPLICATION_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  DRIVE_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  STATUS ENUM('APPLIED', 'SHORTLISTED', 'SELECTED', 'REJECTED', 'WITHDRAWN') NOT NULL DEFAULT 'APPLIED',
  APPLIED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_drive_student (DRIVE_ID, STUDENT_ID),
  CONSTRAINT fk_application_drive FOREIGN KEY (DRIVE_ID) REFERENCES PLACEMENT_DRIVES(DRIVE_ID)
    ON DELETE CASCADE,
  CONSTRAINT fk_application_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS QUESTION_PAPERS (
  PAPER_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  SUBJECT VARCHAR(160) NOT NULL,
  EXAM_YEAR YEAR NOT NULL,
  DOWNLOAD_URL VARCHAR(500) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS RESULTS (
  RESULT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  SUBJECT VARCHAR(160) NOT NULL,
  SCORE DECIMAL(5, 2) NOT NULL,
  MAX_SCORE DECIMAL(5, 2) NOT NULL DEFAULT 100,
  SEMESTER TINYINT UNSIGNED,
  CONSTRAINT fk_results_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ATTENDANCE_SUMMARY (
  ATTENDANCE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL UNIQUE,
  TODAY_PERCENT DECIMAL(5, 2) NOT NULL DEFAULT 0,
  OVERALL_PERCENT DECIMAL(5, 2) NOT NULL DEFAULT 0,
  CONSTRAINT fk_attendance_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS FEEDBACK (
  FEEDBACK_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  SUBJECT VARCHAR(180) NOT NULL,
  MESSAGE TEXT NOT NULL,
  STATUS ENUM('OPEN', 'IN_REVIEW', 'RESOLVED') NOT NULL DEFAULT 'OPEN',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_feedback_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ANNOUNCEMENTS (
  ANNOUNCEMENT_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TITLE VARCHAR(180) NOT NULL,
  MESSAGE TEXT NOT NULL,
  AUDIENCE ENUM('ALL', 'STUDENT', 'FACULTY', 'EMPLOYEE') NOT NULL DEFAULT 'ALL',
  PUBLISHED_BY INT UNSIGNED,
  IS_ACTIVE TINYINT(1) NOT NULL DEFAULT 1,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_announcement_user FOREIGN KEY (PUBLISHED_BY) REFERENCES USERS(USER_ID)
    ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS EMPLOYEE_DASHBOARD_CONFIG (
  CONFIG_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USER_ID INT UNSIGNED NOT NULL,
  DASHBOARD_TYPE ENUM('STUDENT', 'FACULTY', 'STAFF') NOT NULL,
  BACKGROUND VARCHAR(500) NOT NULL,
  SIDEBAR_ITEMS_JSON JSON NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_employee_dashboard_config (USER_ID, DASHBOARD_TYPE),
  CONSTRAINT fk_employee_config_user FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS LIBRARY_CATALOG (
  BOOK_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ISBN VARCHAR(30) UNIQUE,
  TITLE VARCHAR(220) NOT NULL,
  AUTHOR VARCHAR(180) NOT NULL,
  CATEGORY VARCHAR(100),
  TOTAL_COPIES INT UNSIGNED NOT NULL DEFAULT 1,
  AVAILABLE_COPIES INT UNSIGNED NOT NULL DEFAULT 1,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS LIBRARY_ISSUES (
  ISSUE_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  BOOK_ID INT UNSIGNED NOT NULL,
  STUDENT_ID INT UNSIGNED NOT NULL,
  ISSUE_DATE DATE NOT NULL,
  DUE_DATE DATE NOT NULL,
  RETURN_DATE DATE,
  STATUS ENUM('ISSUED', 'RETURNED', 'OVERDUE') NOT NULL DEFAULT 'ISSUED',
  FINE_AMOUNT DECIMAL(10, 2) NOT NULL DEFAULT 0,
  CONSTRAINT fk_library_issue_book FOREIGN KEY (BOOK_ID) REFERENCES LIBRARY_CATALOG(BOOK_ID)
    ON DELETE RESTRICT,
  CONSTRAINT fk_library_issue_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ACCOUNTING_LEDGER (
  LEDGER_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STUDENT_ID INT UNSIGNED NOT NULL,
  DETAIL VARCHAR(180) NOT NULL,
  AMOUNT DECIMAL(10, 2) NOT NULL,
  DUE_DATE DATE,
  TRANSACTION_ID VARCHAR(80),
  STATUS ENUM('PAID', 'UNPAID', 'PENDING', 'WAIVED') NOT NULL DEFAULT 'UNPAID',
  PAID_AT DATETIME,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ledger_student FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
    ON DELETE CASCADE
);
